export const WIN_ON_SITE_DEPOSIT_PERCENT = 25;
export const WIN_ON_SITE_PACKAGE_TIERS = ["good", "better", "best"];

const TIER_CONFIG = {
  good: {
    label: "Good",
    multiplier: 0.85,
    highlights: [
      "Essential scope to get the job done",
      "Standard materials",
      "Estimated timeline",
    ],
  },
  better: {
    label: "Better",
    multiplier: 1,
    highlights: [
      "Recommended scope for most homeowners",
      "Quality materials & finish",
      "Includes cleanup",
    ],
  },
  best: {
    label: "Best",
    multiplier: 1.25,
    highlights: [
      "Premium materials & finish upgrades",
      "Priority scheduling preference",
      "Extended workmanship care",
    ],
  },
};

export function normalizeWinOnSitePackageTier(value, fallback = "better") {
  const tier = String(value || "").trim().toLowerCase();
  if (WIN_ON_SITE_PACKAGE_TIERS.includes(tier)) return tier;
  return fallback;
}

export function roundMoney(value) {
  const n = Number(value);
  if (!Number.isFinite(n) || n <= 0) return 0;
  return Math.round(n * 100) / 100;
}

export function computeDepositAmount(total, percent = WIN_ON_SITE_DEPOSIT_PERCENT) {
  const safeTotal = roundMoney(total);
  const pct = Math.min(100, Math.max(0, Number(percent) || 0));
  if (!(safeTotal > 0) || !(pct > 0)) return 0;
  return roundMoney((safeTotal * pct) / 100);
}

function scaleServices(services, multiplier) {
  return (Array.isArray(services) ? services : []).map((item, idx) => {
    const qty = Math.max(1, Number(item?.qty) || 1);
    const baseUnit = Math.max(0, Number(item?.unitPrice ?? item?.price) || 0);
    const unitPrice = roundMoney(baseUnit * multiplier);
    const price = roundMoney(qty * unitPrice);
    return {
      id: String(item?.id || `pkg_${idx + 1}`),
      name: String(item?.name || `Service ${idx + 1}`).slice(0, 200),
      qty,
      unitPrice,
      price,
      notes: String(item?.notes || "").slice(0, 300),
    };
  });
}

function buildTierPackage(tier, baseDraft) {
  const config = TIER_CONFIG[tier];
  const services = scaleServices(baseDraft?.services, config.multiplier);
  let total = roundMoney(services.reduce((sum, s) => sum + (s.price || 0), 0));

  // If AI returned empty lines, fall back to scaled subtotal.
  if (!(total > 0)) {
    total = roundMoney(Number(baseDraft?.subtotal || 0) * config.multiplier);
    if (total > 0) {
      services.push({
        id: `pkg_${tier}_1`,
        name: String(baseDraft?.title || "Service package").slice(0, 200),
        qty: 1,
        unitPrice: total,
        price: total,
        notes: "",
      });
    }
  }

  return {
    tier,
    label: config.label,
    multiplier: config.multiplier,
    highlights: config.highlights,
    title: String(baseDraft?.title || "").slice(0, 200),
    services,
    total,
    depositPercent: WIN_ON_SITE_DEPOSIT_PERCENT,
    depositAmount: computeDepositAmount(total, WIN_ON_SITE_DEPOSIT_PERCENT),
    estimated: true,
    pricingSource: "multiplier",
    catalogItemIds: [],
  };
}

/**
 * Build Good / Better / Best packages from a base draft estimate.
 * Pure — no I/O.
 */
export function buildWinOnSitePackages(baseDraft = {}) {
  return {
    good: buildTierPackage("good", baseDraft),
    better: buildTierPackage("better", baseDraft),
    best: buildTierPackage("best", baseDraft),
  };
}

export function selectWinOnSitePackage(packages, tier) {
  const normalized = normalizeWinOnSitePackageTier(tier, "better");
  return packages?.[normalized] || packages?.better || null;
}

/** Public-safe package payload (no internal notes noise). */
export function serializeWinOnSitePackagesForPublic(packages) {
  const out = {};
  for (const tier of WIN_ON_SITE_PACKAGE_TIERS) {
    const pkg = packages?.[tier];
    if (!pkg) continue;
    out[tier] = {
      tier: pkg.tier,
      label: pkg.label,
      title: pkg.title,
      highlights: pkg.highlights,
      total: pkg.total,
      depositPercent: pkg.depositPercent,
      depositAmount: pkg.depositAmount,
      estimated: true,
      pricingSource: pkg.pricingSource || "multiplier",
      services: (pkg.services || []).map((s) => ({
        name: s.name,
        qty: s.qty,
        // Hide unit cost details on public cards; show line totals only.
        price: s.price,
      })),
    };
  }
  return out;
}
